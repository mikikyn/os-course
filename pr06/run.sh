## Как подтверждена корректность

После завершения потоков программа не просто смотрит на лог, а проверяет инварианты:

- получено ровно 1000 элементов;
- множество полученных элементов равно `0…999`, поэтому нет потерь и дубликатов;
- размер буфера в конце равен нулю;
- попытки переполнения и чтения пустого буфера записывались бы в `violations` и завершали программу ошибкой;
- для барьера проверяется, что все события `end` фазы N предшествуют любому `start` фазы N+1.

Для завершения потребителей после окончания производителей в буфер помещаются два маркера `None` — по одному на потребителя. Они не входят в пользовательские данные.

## Состояние гонки

В `race_bad.py` операция разложена на чтение старого значения, переключение потока и запись нового значения. Другой поток может успеть изменить счётчик между этими шагами, после чего первый запишет устаревший результат. `time.sleep(0)` лишь делает такое чередование воспроизводимым. В `race_fixed.py` вся критическая секция находится внутри `with lock`, поэтому результат всегда 400000.

## Почему нужен while вокруг wait

`Condition.wait()` может вернуться после сигнала, который не сделал предикат истинным, а также после spurious wakeup. В демонстрации отправляется `notify()` без установки `ready`. Вариант с `if` после возврата не перепроверяет условие и ошибочно продолжает работу. Вариант с `while` снова проверяет `ready` и возвращается к ожиданию, пока данные действительно не появятся.

## Контрольные вопросы

### Чем семафор со значением 1 отличается от мьютекса на практике?

Счётный семафор является примитивом сигнализации и может освобождаться другим потоком. Мьютекс обычно имеет владельца: захвативший поток должен сам его освободить. Бинарный семафор похож на мьютекс по допуску одной критической секции, но не обеспечивает семантику владения и обычно применяется для сигналов между потоками.

### Почему условную переменную нельзя использовать без мьютекса?

Предикат и переход к ожиданию должны быть согласованы с сигналящим потоком. Мьютекс защищает предикат, а `wait()` атомарно освобождает его и засыпает, затем просыпается и снова захватывает. Без мьютекса возможны гонка при проверке состояния и потерянные пробуждения.

