## 1. Алгоритм банкира

Для каждого процесса вычисляется остаточная потребность:

```text
Need = Max − Allocation
```

Проверка безопасности использует копию доступных ресурсов `Work`. Если существует незавершённый процесс с `Need <= Work`, предполагается, что он сможет закончить работу и вернуть ресурсы: `Work += Allocation`. Если так можно завершить все процессы, состояние безопасно.

В `bank1.txt` получен эталонный безопасный порядок `P1 P3 P4 P0 P2`. В `bank2.txt` доступных ресурсов недостаточно даже для первого процесса, поэтому состояние `UNSAFE`.

Перед выдачей ресурсов запрос проверяется по трем условиям: он не превышает `Need`, не превышает `Available`, а временное выделение оставляет систему в безопасном состоянии. При небезопасном результате `Available` и `Allocation` восстанавливаются — это откат запроса. В запуске запрос `P1 [1,0,2]` разрешён, а `P4 [3,3,0]` и `P0 [0,2,0]` отклонены.

Безопасное состояние не означает отсутствие любых ожиданий: оно означает, что существует хотя бы один порядок завершения всех процессов без взаимоблокировки.

## 2. Детектор по графу ожидания

Из событий `acquire`, `wait` и `release` строится граф: ребро `Pi -> Pj` означает, что `Pi` ждёт ресурс, которым владеет `Pj`. Поиск в глубину хранит посещённые вершины и текущий стек; повторный переход к вершине из стека даёт цикл.

Для `deadlock.log` найден цикл `P1 -> P2 -> P1`, для `safe.log` цикла нет. Для ресурсов с одним экземпляром цикл в wait-for graph является необходимым и достаточным признаком deadlock. При нескольких экземплярах одного ресурса одного цикла недостаточно — нужен более подробный анализ.

## 3. TrackedLock и намеренный deadlock

`deadlock_naive.py` использует обычные блокировки: `P1` удерживает A и ждёт B, а `P2` удерживает B и ждёт A. Оба потока остаются заблокированными, поэтому внешний `timeout` завершает программу с кодом `124`.

`TrackedLock` перед реальным ожиданием добавляет ребро в общий граф ожидания. Если появляется цикл, новое ребро удаляется и выбрасывается `DeadlockDetected`, а блокировка не выполняется. Второй поток после освобождения ресурса завершает работу. Таким образом, цикл превращается в управляемую ошибку вместо зависания.

## 4. Обедающие философы

- `naive`: каждый философ сначала берёт левую вилку, затем ждёт правую. Барьер гарантирует, что все пять удержат левые вилки одновременно; возникает круговое ожидание, и сценарий намеренно не завершается.
- `ordered`: вилки всегда захватываются в порядке возрастания их номеров. Глобальный порядок ресурсов исключает цикл, все философы едят по 20 раз.
- `waiter`: семафор пропускает за стол не более четырёх философов из пяти. Поэтому хотя бы одна вилка остаётся доступной для продвижения, все философы также едят по 20 раз.

## Контрольные вопросы

### Четыре условия Коффмана

1. **Взаимное исключение:** ресурс одновременно принадлежит не более чем одному процессу.
2. **Удержание и ожидание:** процесс удерживает один ресурс и ждёт другой.
3. **Отсутствие принудительного освобождения:** ресурс нельзя забрать до добровольного освобождения владельцем.
4. **Круговое ожидание:** существует цепочка процессов, где каждый ждёт ресурс следующего.

Deadlock возможен только при одновременном выполнении всех четырёх условий. Предотвращение устраняет хотя бы одно из них: `ordered` и `waiter` разрушают круговое ожидание.

### Чем предотвращение, избегание и обнаружение различаются?

| Подход | Идея | Пример в работе |
|---|---|---|
| Предотвращение | Заранее исключить одно из условий Коффмана | Глобальный порядок вилок |
| Избегание | Перед выделением проверить, останется ли состояние безопасным | Алгоритм банкира |
| Обнаружение и восстановление | Разрешить запросы, периодически искать deadlock и затем устранять его | Цикл в графе и исключение `TrackedLock` |

