#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

RESULTS="results.txt"
: > "$RESULTS"
exec 3>&1 4>&2
exec > >(tee -a "$RESULTS") 2>&1

expect_timeout() {
    local label="$1"
    shift
    set +e
    timeout 3s "$@"
    local status=$?
    set -e
    printf '%s: exit=%s (ожидалось 124)\n' "$label" "$status"
    if [[ "$status" -ne 124 ]]; then
        echo "ОШИБКА: $label должен был зависнуть до timeout" >&2
        return 1
    fi
}

echo "=== ПР-8, вариант B: взаимоблокировки ==="
date
echo '$ python3 --version'
python3 --version
echo

echo '$ python3 banker.py bank1.txt'
python3 banker.py bank1.txt
echo

echo '$ python3 banker.py bank2.txt'
python3 banker.py bank2.txt
echo

echo "$ printf 'P1 1 0 2\\nP4 3 3 0\\nP0 0 2 0\\n' | python3 banker.py bank1.txt"
printf 'P1 1 0 2\nP4 3 3 0\nP0 0 2 0\n' | python3 banker.py bank1.txt
echo

echo '$ python3 detector.py deadlock.log'
python3 detector.py deadlock.log
echo '$ python3 detector.py safe.log'
python3 detector.py safe.log
echo

echo '$ timeout 3s python3 deadlock_naive.py'
expect_timeout 'deadlock_naive.py' python3 deadlock_naive.py
echo

echo '$ python3 deadlock.py'
python3 deadlock.py
echo

echo '$ timeout 3s python3 philosophers.py --mode naive'
expect_timeout 'philosophers.py --mode naive' python3 philosophers.py --mode naive
echo

echo '$ python3 philosophers.py --mode ordered'
python3 philosophers.py --mode ordered
echo '$ python3 philosophers.py --mode waiter'
python3 philosophers.py --mode waiter
echo

echo '=== Автоматическая проверка ==='
grep -q '^SAFE, P1 P3 P4 P0 P2$' "$RESULTS"
grep -q '^UNSAFE$' "$RESULTS"
grep -q '^request P1 \[1,0,2\]: GRANT$' "$RESULTS"
grep -q '^request P4 \[3,3,0\]: DENY$' "$RESULTS"
grep -q '^request P0 \[0,2,0\]: DENY$' "$RESULTS"
grep -q '^DEADLOCK: P1 -> P2 -> P1$' "$RESULTS"
grep -q '^NO DEADLOCK$' "$RESULTS"
grep -q '^deadlock_naive.py: exit=124 (ожидалось 124)$' "$RESULTS"
grep -q 'DEADLOCK предотвращён: P1 -> P2 -> P1' "$RESULTS"
grep -q '^OK TrackedLock: потоки завершились без deadlock$' "$RESULTS"
grep -q '^philosophers.py --mode naive: exit=124 (ожидалось 124)$' "$RESULTS"
grep -q '^OK ordered: meals=\[20, 20, 20, 20, 20\]$' "$RESULTS"
grep -q '^OK waiter: meals=\[20, 20, 20, 20, 20\]$' "$RESULTS"
echo 'OK: эталоны банкира, циклы, намеренные зависания и оба решения философов проверены.'

