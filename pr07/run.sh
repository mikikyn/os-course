## Сравнение механизмов

| Механизм | Синхронизация со стороны программиста | Объём и модель данных |
|---|---|---|
| FIFO | Нужен протокол запроса/ответа и аккуратное открытие двух концов; для одновременных клиентов нужны дополнительные каналы или сериализация | Поток байтов, в демо короткие строки |
| Unix socket | ОС управляет соединениями и буферами; сервер выделяет поток на клиента | Надёжный двунаправленный поток, несколько одновременных клиентов |
| Pipe | ОС доставляет целые сообщения через `multiprocessing`; ручная синхронизация чтения/записи не нужна | В бенчмарке 40 000 000 байт с сериализацией и копированием |
| Shared memory | При одновременном чтении и записи нужны семафоры/мьютексы; здесь запись завершена до запуска читателя | Те же 10 000 000 чисел, читатель обращается к общим страницам без отправки копии |

Время зависит от машины, поэтому выводится фактическая таблица запуска. Время shared memory включает запуск дочернего процесса, присоединение к уже заполненному сегменту и чтение; время Pipe включает запуск процесса, сериализацию, передачу и чтение массива.

## Очистка ресурсов

Серверы в `finally` удаляют FIFO и socket. Сегмент shared memory закрывается и удаляется только родителем после завершения ребёнка. Для процессов выбран `spawn`, поэтому нет конфликта сырого `fork` с `resource_tracker` из `multiprocessing.shared_memory`. Автоматическая проверка также удаляет рабочий каталог `.ipc`.

## Контрольные вопросы

### Почему разделяемая память — самый быстрый и самый опасный механизм IPC?

Процессы читают одни физические страницы без повторного копирования большого массива через ядро. Но ядро не упорядочивает произвольные обращения к этим данным: при одновременной записи и чтении возможны гонки и повреждённые промежуточные состояния, поэтому нужна синхронизация.

### Что произойдёт при записи в pipe, у которого закрыты все читающие концы?

Ядро отправит пишущему процессу сигнал `SIGPIPE`, по умолчанию завершающий его. Если сигнал обработан или игнорируется, `write` вернёт ошибку `EPIPE`.

