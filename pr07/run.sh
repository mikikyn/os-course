date
echo '$ python3 --version'
python3 --version
echo

echo '$ python3 fifo_demo.py'
python3 fifo_demo.py
echo

echo '$ python3 socket_demo.py'
python3 socket_demo.py
echo

echo '$ python3 shm_benchmark.py'
python3 shm_benchmark.py
echo

echo '=== Автоматическая проверка ==='
[[ ! -e .ipc ]]
grep -q 'FIFO удалены' "$RESULTS"
grep -q 'сокет удалён' "$RESULTS"
grep -q 'сегмент shared memory закрыт и удалён' "$RESULTS"
echo 'OK: FIFO, параллельные socket-клиенты, 10^7 чисел и очистка ресурсов проверены.'

exec 1>&3 2>&4

cat > README.md <<'EOF'
